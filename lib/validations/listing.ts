import { z } from "zod";
import { AMENITIES, MAX_CUSTOM_AMENITIES, PROPERTY_TYPES, type Amenity, type PropertyType } from "@/lib/listings/constants";

// Shared by the create/edit form (client) and the Server Actions (server).
// The database enforces the same limits with check constraints.

export const IMAGE_TYPES = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" } as const;
export type ImageContentType = keyof typeof IMAGE_TYPES;
export const MAX_IMAGES = 10;
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
export const MAX_AVATAR_BYTES = 2 * 1024 * 1024;

/** <owner user id>/<random uuid>.<ext>, as generated by the upload action. */
export const STORAGE_PATH_PATTERN = /^[0-9a-f-]{36}\/[0-9a-f-]{36}\.(jpg|png|webp)$/;

const propertyTypes = PROPERTY_TYPES.map((type) => type.value) as [PropertyType, ...PropertyType[]];
const amenityValues = AMENITIES.map((amenity) => amenity.value) as [Amenity, ...Amenity[]];

const text = (label: string, max: number) =>
  z
    .string()
    .trim()
    .min(1, `Enter ${label}.`)
    .max(max, `Keep ${label} to ${max.toLocaleString("en-US")} characters or fewer.`);

const wholeNumber = (label: string, min: number, max: number) =>
  z
    .number({ error: `Enter ${label}.` })
    .int("Use a whole number.")
    .min(min, `Must be at least ${min}.`)
    .max(max, `Must be ${max} or fewer.`);

const money = (label: string) =>
  z
    .number({ error: `Enter ${label}.` })
    .min(0, "Can't be negative.")
    .max(1_000_000, "That's too much, even for a fictional place.")
    .refine((value) => Math.abs(value * 100 - Math.round(value * 100)) < 1e-6, "Use at most two decimal places.");

export const listingImageSchema = z.object({
  path: z.string().regex(STORAGE_PATH_PATTERN, "Invalid photo."),
  isPrimary: z.boolean(),
});
export type ListingImageValue = z.infer<typeof listingImageSchema>;

export const listingDetailsSchema = z.object({
  // Step 1: basics
  title: text("a title", 100),
  description: text("a description", 3000),
  property_type: z.enum(propertyTypes, { error: "Choose a property type." }),
  city: text("a city", 100),
  country: text("a country", 100),
  // Step 2: details
  max_guests: wholeNumber("the maximum number of guests", 1, 50),
  bedrooms: wholeNumber("the number of bedrooms", 0, 50),
  beds: wholeNumber("the number of beds", 0, 100),
  bathrooms: z
    .number({ error: "Enter the number of bathrooms." })
    .min(0, "Can't be negative.")
    .max(50, "Must be 50 or fewer.")
    .refine((value) => Number.isInteger(value * 2), "Use whole or half bathrooms, like 1 or 1.5."),
  nightly_price: money("a nightly price"),
  cleaning_fee: money("a cleaning fee"),
  service_fee: money("a service fee"),
  // Step 3: amenities
  amenities: z.object({
    standard: z.array(z.enum(amenityValues)).refine((list) => new Set(list).size === list.length, "Duplicate amenity."),
    custom: z
      .array(z.string().trim().min(1, "Enter an amenity.").max(40, "Keep custom amenities to 40 characters."))
      .max(MAX_CUSTOM_AMENITIES, `Add up to ${MAX_CUSTOM_AMENITIES} custom amenities.`)
      .refine(
        (list) => new Set(list.map((item) => item.toLowerCase())).size === list.length,
        "Each custom amenity must be different.",
      ),
  }),
  // Step 4: photos
  images: z
    .array(listingImageSchema)
    .min(1, "Add at least one photo.")
    .max(MAX_IMAGES, `You can add up to ${MAX_IMAGES} photos.`)
    .refine((images) => images.filter((image) => image.isPrimary).length === 1, "Choose a cover photo.")
    .refine((images) => new Set(images.map((image) => image.path)).size === images.length, "Duplicate photo."),
});

// Step 5: confirmations, required every time a listing is published or saved.
export const listingFormSchema = listingDetailsSchema.extend({
  confirmFictional: z.boolean().refine((value) => value, "Please confirm that this listing is fictional."),
  confirmImageRights: z
    .boolean()
    .refine((value) => value, "Please confirm you have permission to use these photos."),
});

export type ListingFormValues = z.infer<typeof listingFormSchema>;

export const LISTING_FORM_STEPS = [
  { title: "Basics", fields: ["title", "description", "property_type", "city", "country"] },
  {
    title: "Details",
    fields: ["max_guests", "bedrooms", "beds", "bathrooms", "nightly_price", "cleaning_fee", "service_fee"],
  },
  { title: "Amenities", fields: ["amenities"] },
  { title: "Photos", fields: ["images"] },
  { title: "Preview", fields: ["confirmFictional", "confirmImageRights"] },
] as const satisfies readonly { title: string; fields: readonly (keyof ListingFormValues)[] }[];

/** The step that owns a field, for jumping to the first error. */
export function stepForField(field: string): number {
  const root = field.split(".")[0];
  const index = LISTING_FORM_STEPS.findIndex((step) => (step.fields as readonly string[]).includes(root));
  return index === -1 ? 0 : index;
}

/** Shape expected by the create_listing / update_listing database functions. */
export function toDatabasePayload(values: z.infer<typeof listingDetailsSchema>) {
  const { images, ...listing } = values;
  return {
    listing,
    images: images.map((image) => ({ storage_path: image.path, is_primary: image.isPrimary })),
  };
}
